using System.Reflection;

namespace Win8Xaml.CompilerProxies
{
    public static class HotReloadRetiredMembers
    {
        private static readonly MethodInfo CreateInventoryMethod;
        private static readonly MethodInfo RestoreMethod;

        static HotReloadRetiredMembers()
        {
            var type = new ProxyHelper("Microsoft.UI.Xaml.Markup.Compiler.HotReloadRetiredMembers");
            CreateInventoryMethod = type.GetMethod("CreateInventory", BindingFlags.NonPublic | BindingFlags.Static);
            RestoreMethod = type.GetMethod("Restore", BindingFlags.NonPublic | BindingFlags.Static);
        }

        // The C# generated by a later compile, with the fields and nested types that `previousCode` had and it lacks
        // restored as tombstones.
        public static string Restore(string code, string previousCode)
        {
            object inventory = CreateInventoryMethod.Invoke(null, new object[] { previousCode });
            return (string)RestoreMethod.Invoke(null, new object[] { code, inventory });
        }
    }
}
